  const root = document.documentElement;
  const originals = new WeakMap();
  const attributes = new WeakMap();
  let language = 'pt';
  try { const saved = localStorage.getItem('blue-moby-language'); if (['pt', 'en', 'zh'].includes(saved)) language = saved; } catch { }
  const normalise = text => text.trim().replace(/\s+/g, ' ');
  function translate(source) {
    if (language === 'pt') return source;
    if (dictionary[source]) return dictionary[source][language];
    const count = source.match(/^(\d+) peças? na seleção$/);
    if (count) return language === 'zh' ? `已选 ${count[1]} 件产品` : `${count[1]} ${count[1] === '1' ? 'piece' : 'pieces'} in this selection`;
    const product = source.match(/^(Cômoda|Cozinha|Home Painel|Gabinete|Conjunto) (Miami|Tati|Havana|Caribe|Flora|Amanda)$/);
    if (product) return `${translate(product[1])} ${product[2]}`;
    if (source.startsWith('Ver detalhes de ')) return (language === 'zh' ? '查看详情：' : 'View details of ') + translate(source.slice(16));
    if (source.startsWith('Copie este nome: ')) return (language === 'zh' ? '请复制此名称：' : 'Copy this name: ') + source.slice(16);
    return source;
  }
  function updateText(node) {
    if (!node.textContent.trim() || node.parentElement?.closest('script,style,[data-language]')) return;
    let record = originals.get(node);
    if (!record || node.data !== record.rendered) record = { source: node.data };
    const source = normalise(record.source);
    const translated = translate(source);
    record.rendered = language === 'pt' ? record.source : record.source.match(/^\s*/)[0] + translated + record.source.match(/\s*$/)[0];
    originals.set(node, record);
    if (node.data !== record.rendered) node.data = record.rendered;
  }
  function updateAttributes(element) {
    if (element.matches('[data-language]')) return;
    const saved = attributes.get(element) || {};
    for (const name of ['aria-label', 'alt', 'title', ...(element.matches('meta[name="description"]') ? ['content'] : [])]) {
      if (!element.hasAttribute(name)) continue;
      const value = element.getAttribute(name);
      if (!saved[name] || value !== saved[name].rendered) saved[name] = { source: value };
      saved[name].rendered = translate(normalise(saved[name].source));
      if (value !== saved[name].rendered) element.setAttribute(name, saved[name].rendered);
    }
    attributes.set(element, saved);
  }
  function translateTree(node) {
    if (node.nodeType === Node.TEXT_NODE) { updateText(node); return; }
    if (node.nodeType !== Node.ELEMENT_NODE) return;
    updateAttributes(node);
    const walker = document.createTreeWalker(node, NodeFilter.SHOW_TEXT);
    while (walker.nextNode()) updateText(walker.currentNode);
    node.querySelectorAll('[aria-label],[alt],[title],meta[name="description"]').forEach(updateAttributes);
  }
  const observer = new MutationObserver(records => {
    observer.disconnect();
    for (const record of records) {
      if (record.type === 'childList') record.addedNodes.forEach(translateTree);
      else if (record.type === 'characterData') updateText(record.target);
      else updateAttributes(record.target);
    }
    observe();
  });
  function observe() { observer.observe(root, { subtree: true, childList: true, characterData: true, attributes: true, attributeFilter: ['aria-label', 'alt', 'title', 'content'] }); }
